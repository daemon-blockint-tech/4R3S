//! `evidence_registry` -- anchors an ARES evidence Merkle root on Solana.
//!
//! # NEVER COMPILED, NEVER DEPLOYED
//!
//! This source has not been built to SBF and no cluster carries this program.
//! There is no `solana` CLI, no `anchor` CLI and no `cargo build-sbf` in this
//! repository's CI or on the machine it was written on. What *is* mechanically
//! checked is the specification it implements: every constant, offset and
//! preimage lives in `evidence-registry-spec`, which compiles and tests on the
//! host target, and `tests/program_source_conformance.rs` parses this file with
//! `syn` and asserts it matches that table.
//!
//! So the honest claim is: **the constraints below are asserted to be declared,
//! not proven to be enforced.** Proving enforcement needs `anchor test` against a
//! localnet, which is a deferred task. See `../../../README.md`.
//!
//! # What this program does
//!
//! Stores a 32-byte root. It does **not** verify Merkle proofs -- it cannot see
//! the leaves, and no on-chain party benefits from re-deriving a root it has no
//! inputs for. Proof verification is a client operation. An anchor's whole job is
//! to timestamp 32 bytes against a clock the submitter does not control.
//!
//! # What an anchor proves, and does not
//!
//! Proves: the holder of `authority` published this `(root, leaf_count,
//! report_sha256, target_binding)` tuple in a transaction included at some slot.
//! That is an *upper bound on when the root was known*, and nothing more.
//!
//! Does not prove the audit happened, was competent, or was complete -- the chain
//! sees 32 bytes and cannot tell a real audit from `sha256(random)`. Does not
//! prove findings were not withheld: you can prove a finding *was* in the
//! committed set, never that one was not held back. Does not prove `authority`
//! is who they claim. Does not prove the root concerns the claimed target, since
//! `target_binding` is self-asserted and anyone can anchor anything for ~0.002
//! SOL. Does not give a *lower* bound on time.
//!
//! Every immutability claim here is also conditional on the upgrade authority
//! being renounced. An upgrade authority can deploy a version with an
//! arbitrary-write instruction and rewrite any record, so
//! `set-upgrade-authority --final` must happen before the first real anchor --
//! and renouncing later does not retroactively secure earlier anchors, because a
//! different binary may have been deployed in the interim. ARES's own detector
//! flags `upgrade-authority-risk`; an ARES-authored program that stays upgradeable
//! fails its own audit.

use anchor_lang::prelude::*;
use evidence_registry_spec::{commitment, layout, merkle, seeds};

